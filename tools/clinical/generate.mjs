import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { validateCatalog } from './validate.mjs';
import { renderSql } from './sql.mjs';
import { projectEntries } from './project.mjs';
export { projectEntries } from './project.mjs';

const root = new URL('../../', import.meta.url);
export const artifact = 'src/lib/biomarkers/catalog.generated.ts';
export function readCatalog() {
  return validateCatalog(JSON.parse(readFileSync(new URL('clinical/catalog/catalog.json', root), 'utf8')));
}
export function renderCatalog(catalog = readCatalog()) {
  const template = readFileSync(new URL('tools/clinical/dictionary.template.ts.txt', root), 'utf8');
  if (template.split('__ENTRIES__').length !== 2) throw new Error('Template needs exactly one entries marker');
  return '// Generated by npm run clinical:generate. Edit clinical/catalog/catalog.json.\n'
    + '// Legacy API preserves shipping values; optimal is not a provenance endorsement.\n'
    + template.replace('__ENTRIES__', () => JSON.stringify(projectEntries(catalog), null, 2));
}
export function checkArtifact(expected, actual) {
  if (expected !== actual) throw new Error(`${artifact} drifted; run npm run clinical:generate`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = readCatalog();
  for (const [name, expected] of Object.entries({ [artifact]: renderCatalog(catalog), ...renderSql(catalog) })) {
    const path = new URL(name, root);
    if (process.argv.includes('--check')) {
      if (expected !== readFileSync(path, 'utf8')) throw new Error(`${name} drifted; run npm run clinical:generate`);
    } else writeFileSync(path, expected);
  }
  console.log(`Clinical catalog ${process.argv.includes('--check') ? 'matches' : 'generated'} (${readCatalog().analytes.length} entries)`);
}
