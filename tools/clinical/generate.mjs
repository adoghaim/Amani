import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { validateCatalog } from './validate.mjs';
import { renderSql, renderReviewSql, reviewMigrationArtifact, reviewRollbackArtifact, reviewVerifyArtifact } from './sql.mjs';
import { projectEntries, projectContext, projectUnitEquivalences } from './project.mjs';
export { projectEntries, projectContext, projectUnitEquivalences } from './project.mjs';

const root = new URL('../../', import.meta.url);
export const artifact = 'src/lib/biomarkers/catalog.generated.ts';
export const contextArtifact = 'src/lib/biomarkers/rangeContext.generated.ts';
// TASK-044 owner GO authorizes creating these, once. After creation they are
// frozen like V2-01: a changed seed needs another new, separately authorized migration.
export const creatableArtifacts = [reviewMigrationArtifact, reviewRollbackArtifact, reviewVerifyArtifact];
export function readCatalog() {
  const catalog = validateCatalog(JSON.parse(readFileSync(new URL('clinical/catalog/catalog.json', root), 'utf8')));
  assertAuditInventory(catalog);
  return catalog;
}
// Production seed inventory, separate from validation of synthetic candidate fixtures.
export function assertAuditInventory(catalog) {
  const ranges = catalog.analytes.reduce((count, a) => count + a.ranges.filter(r => !r.candidate_id).length, 0);
  if (catalog.analytes.length !== 83 || ranges !== 198) throw new Error(`TASK-042 requires 83 analytes / 198 ranges (shipping only); found ${catalog.analytes.length}/${ranges}`);
}
export function renderCatalog(catalog = readCatalog()) {
  const template = readFileSync(new URL('tools/clinical/dictionary.template.ts.txt', root), 'utf8');
  if (template.split('__ENTRIES__').length !== 2) throw new Error('Template needs exactly one entries marker');
  return '// Generated by npm run clinical:generate. Edit clinical/catalog/catalog.json.\n'
    + '// Legacy API preserves shipping values; optimal is not a provenance endorsement.\n'
    + template.replace('__ENTRIES__', () => JSON.stringify(projectEntries(catalog), null, 2));
}
export function renderContext(catalog = readCatalog()) {
  const template = readFileSync(new URL('tools/clinical/context.template.ts.txt', root), 'utf8');
  if (template.split('__CONTEXT__').length !== 2) throw new Error('Template needs exactly one context marker');
  if (template.split('__UNIT_EQUIVALENCES__').length !== 2) throw new Error('Template needs exactly one unit equivalence marker');
  return '// Generated by npm run clinical:generate. Edit clinical/catalog/catalog.json.\n'
    + '// Review state, context flags and approved unit equivalences; band values live in catalog.generated.ts.\n'
    + template.replace('__CONTEXT__', () => JSON.stringify(projectContext(catalog), null, 2))
      .replace('__UNIT_EQUIVALENCES__', () => JSON.stringify(projectUnitEquivalences(catalog), null, 2));
}
export function checkArtifact(expected, actual) {
  if (expected !== actual) throw new Error(`${artifact} drifted; run npm run clinical:generate`);
}
const readOrNull = name => {
  try { return readFileSync(new URL(name, root), 'utf8'); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
};
// Preflight all artifacts before any write: a frozen mismatch must leave even
// mutable artifacts untouched. Injected I/O permits regression tests without
// touching the frozen repository files. This is not crash-safe multi-file I/O.
// A read of null means the file is absent; only listed creatable artifacts may
// then be written, and never once they exist.
export function generateArtifacts(catalog, { check = false, read = readOrNull, write = (name, content) => writeFileSync(new URL(name, root), content) } = {}) {
  const outputs = { [artifact]: renderCatalog(catalog), [contextArtifact]: renderContext(catalog), ...renderSql(catalog), ...renderReviewSql(catalog) };
  const changes = Object.entries(outputs).map(([name, expected]) => [name, expected, read(name)]).filter(([, expected, actual]) => actual !== expected);
  for (const [name, , actual] of changes) {
    if (check) throw new Error(`${name} drifted; run npm run clinical:generate`);
    if (name.startsWith('supabase/') && !(actual === null && creatableArtifacts.includes(name))) {
      throw new Error(`${name} is frozen; a new migration requires separate authorization`);
    }
  }
  for (const [name, expected] of changes) write(name, expected);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = readCatalog();
  generateArtifacts(catalog, { check: process.argv.includes('--check') });
  console.log(`Clinical catalog ${process.argv.includes('--check') ? 'matches' : 'generated'} (${catalog.analytes.length} entries)`);
}
