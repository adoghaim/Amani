import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { validateCatalog } from './validate.mjs';

const root = new URL('../../', import.meta.url);
export const artifact = 'src/lib/biomarkers/catalog.generated.ts';
export function readCatalog() {
  return validateCatalog(JSON.parse(readFileSync(new URL('clinical/catalog/catalog.json', root), 'utf8')));
}
export function projectEntries(catalog) {
  validateCatalog(catalog);
  return catalog.analytes.map(a => {
    const band = (kind, phase) => {
      const r = a.ranges.find(r => r.kind === kind && r.phase === phase);
      return { min: r.min, max: r.max };
    };
    const entry = { key: a.slug, displayName: a.display_name, aliases: a.aliases,
      defaultUnit: a.canonical_unit, category: a.category, importance: a.importance,
      optimal: band('amani_context', null), clinical: band('lab_reference', null) };
    const phases = [...new Set(a.ranges.map(r => r.phase).filter(p => p !== null))];
    if (phases.length) entry.phaseRanges = Object.fromEntries(phases.map(phase => [phase,
      { optimal: band('amani_context', phase), clinical: band('lab_reference', phase) }]));
    if ('higher_is_better' in a) entry.higherIsBetter = a.higher_is_better;
    return entry;
  });
}
export function renderCatalog(catalog = readCatalog()) {
  const template = readFileSync(new URL('tools/clinical/dictionary.template.ts.txt', root), 'utf8');
  if (template.split('__ENTRIES__').length !== 2) throw new Error('Template needs exactly one entries marker');
  return '// Generated by npm run clinical:generate. Edit clinical/catalog/catalog.json.\n'
    + '// Legacy API preserves shipping values; optimal is not a provenance endorsement.\n'
    + template.replace('__ENTRIES__', JSON.stringify(projectEntries(catalog), null, 2));
}
export function checkArtifact(expected, actual) {
  if (expected !== actual) throw new Error(`${artifact} drifted; run npm run clinical:generate`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderCatalog();
  const path = new URL(artifact, root);
  if (process.argv.includes('--check')) checkArtifact(expected, readFileSync(path, 'utf8'));
  else writeFileSync(path, expected);
  console.log(`Clinical catalog ${process.argv.includes('--check') ? 'matches' : 'generated'} (${readCatalog().analytes.length} entries)`);
}
